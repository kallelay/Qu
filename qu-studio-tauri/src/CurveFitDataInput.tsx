import React, { useEffect, useMemo } from 'react';
import { EXAMPLES, columnStats, parseTable, type Shape, type Table } from './curveFitData';
import type { FitSpec } from './curveFitDesign';
import { formatSig } from './dataTable';
import { DataSourcePicker, PreviewTable, inDesktopApp, pickTableFile, type SourceKind } from './DataSourcePicker';

const SOURCE_KINDS: Array<{ id: SourceKind; label: string }> = [
  { id: 'example', label: 'Built-in example (generated by Qu)' },
  { id: 'paste', label: 'Paste text / CSV' },
  { id: 'file', label: 'CSV file from disk' },
  { id: 'variable', label: 'Variables from the last Code run' },
];

/** The slice of the fit spec the data input owns. */
export type DataSlice = Pick<FitSpec, 'shape' | 'source' | 'table' | 'filePath' | 'example' | 'cols' | 'weight'>;

/** UI-only state that must survive a trip to another tab but is not part of the script. */
export interface DataUi {
  pasteText: string;
  varNames: string[];
  note: string;
}

export interface CurveFitDataProps {
  value: DataSlice;
  ui: DataUi;
  onChange: (patch: Partial<DataSlice>) => void;
  onUi: (patch: Partial<DataUi>) => void;
  invoke: <T,>(command: string, args?: Record<string, any>) => Promise<T>;
  /** Numeric vectors of the Code tab's last run, usable as columns. */
  signalVars?: Array<{ name: string; length: number }>;
  loadSignal?: (name: string) => Promise<(number | null)[]>;
}

const border = 'var(--qu-border)';
const inputClass = 'px-2 py-1.5 rounded-md text-sm bg-transparent border';

/** Sensible first column choices for a table, by data shape. */
export function autoCols(shape: Shape, table: Table | null, prev: FitSpec['cols']): FitSpec['cols'] {
  const names = table?.columns.map((c) => c.name) ?? [];
  const keep = (v: string) => (names.includes(v) ? v : '');
  const pick = (i: number) => names[i] ?? '';
  const t = keep(prev.t) || pick(0);
  const signals = prev.signals.filter((s) => names.includes(s) && s !== t);
  return {
    x: keep(prev.x) || pick(0),
    y: keep(prev.y) || pick(1),
    z: keep(prev.z) || pick(2),
    err: keep(prev.err),
    t,
    signals: signals.length ? signals : names.filter((n) => n !== t).slice(0, 3),
  };
}

const SHAPES: Array<{ id: Shape; label: string; hint: string }> = [
  { id: 'yx', label: 'y(x)', hint: 'one column against another' },
  { id: 'surface', label: 'z(x, y)', hint: 'a surface over two inputs' },
  { id: 'multi', label: 'signals over time', hint: 'several columns against a time column' },
];
export const shapeOptions = SHAPES;

export const CurveFitData: React.FC<CurveFitDataProps> = ({ value, ui, onChange, onUi, invoke, signalVars = [], loadSignal }) => {
  const table = value.table;
  const names = table?.columns.map((c) => c.name) ?? [];

  const setTable = (t: Table | null, extra: Partial<DataSlice> = {}) => onChange({ table: t, cols: autoCols(value.shape, t, value.cols), ...extra });

  // pasted text -> table, as the text changes
  useEffect(() => {
    if (value.source !== 'paste') return;
    const t = ui.pasteText.trim() === '' ? null : parseTable(ui.pasteText);
    setTable(t && t.columns.length ? t : t);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [ui.pasteText, value.source]);

  // chosen session variables -> table
  useEffect(() => {
    if (value.source !== 'variable') return;
    if (!loadSignal || ui.varNames.length === 0) {
      setTable(null);
      onUi({ note: ui.varNames.length === 0 ? 'Tick the variables to use as columns.' : '' });
      return;
    }
    let live = true;
    (async () => {
      try {
        const data = await Promise.all(ui.varNames.map((n) => loadSignal(n)));
        if (!live) return;
        const rows = Math.min(...data.map((d) => d.length));
        const longest = Math.max(...data.map((d) => d.length));
        const t: Table = {
          columns: ui.varNames.map((name, i) => ({ name, values: data[i].slice(0, rows).map((v) => (v == null ? NaN : v)) })),
          rows, header: true, delimiter: 'session', problems: [],
        };
        if (rows !== longest) t.problems.push(`The variables have different lengths: only the first ${rows} samples of each are used.`);
        setTable(t);
        onUi({ note: '' });
      } catch (err) {
        if (live) onUi({ note: `Could not read the variables: ${err}` });
      }
    })();
    return () => {
      live = false;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [value.source, ui.varNames, signalVars, loadSignal]);

  /** The native dialog + the engine's file reader; 'fallback' asks the picker for the browser's file input. */
  const chooseFile = async (): Promise<'handled' | 'fallback'> => {
    if (!inDesktopApp()) return 'fallback';
    try {
      const path = await pickTableFile('Tables', ['csv', 'txt', 'tsv', 'dat']);
      if (!path) return 'handled';
      const text = await invoke<string>('open_file', { path });
      setTable(parseTable(text), { filePath: path });
      onUi({ note: `Read ${path}` });
    } catch (err) {
      onUi({ note: `Could not open the file: ${err}` });
    }
    return 'handled';
  };

  const stats = useMemo(() => (table ? table.columns.map((c) => ({ name: c.name, s: columnStats(c.values) })) : []), [table]);
  const select = (label: string, v: string, set: (s: string) => void, opts: string[], allowNone = false) => (
    <label className="flex flex-col gap-1 text-xs flex-1 min-w-0">
      <span style={{ color: 'var(--qu-muted)' }}>{label}</span>
      <select value={v} onChange={(e) => set(e.target.value)} className={inputClass} style={{ borderColor: border }}>
        {allowNone && <option value="">none</option>}
        {!allowNone && v === '' && <option value="">pick...</option>}
        {opts.map((o) => <option key={o} value={o}>{o}</option>)}
      </select>
    </label>
  );
  const setCol = (patch: Partial<FitSpec['cols']>) => onChange({ cols: { ...value.cols, ...patch } });
  const ex = EXAMPLES.filter((e) => e.shape === value.shape);

  const exInfo = ex.find((e) => e.id === value.example);
  const shapeStrip = (
    <div className="flex gap-1" role="tablist" aria-label="Data shape">
      {SHAPES.map((s) => (
        <button
          key={s.id}
          role="tab"
          aria-selected={value.shape === s.id}
          title={s.hint}
          className="qu-side-action flex-1"
          style={value.shape === s.id ? { background: 'var(--qu-accent)', color: '#fff' } : undefined}
          onClick={() => {
            const e = EXAMPLES.find((x) => x.shape === s.id);
            onChange({ shape: s.id, cols: autoCols(s.id, table, value.cols), ...(value.source === 'example' && e ? { example: e.id } : {}) });
          }}
        >
          {s.label}
        </button>
      ))}
    </div>
  );
  const hasTable = value.source !== 'example' && table && table.columns.length > 0;

  return (
    <div className="flex flex-col gap-2">
      <DataSourcePicker
        before={shapeStrip}
        chooser="select"
        kinds={SOURCE_KINDS}
        kind={value.source}
        onKind={(source) => {
          const first = ex[0]?.id ?? value.example;
          onChange({ source, ...(source === 'example' ? { example: ex.some((x) => x.id === value.example) ? value.example : first } : {}) });
        }}
        example={
          <>
            {select('Example', value.example, (v) => onChange({ example: v }), ex.map((e) => e.id))}
            <p className="text-xs" style={{ color: 'var(--qu-muted)' }}>{exInfo?.label}: {exInfo?.note}. Seeded, so it is the same every time.</p>
          </>
        }
        paste={{
          value: ui.pasteText,
          onChange: (pasteText) => onUi({ pasteText }),
          placeholder: 'x,y\n1,2.1\n2,3.9\n3,6.2\n(commas, tabs, semicolons or spaces; a header line is optional)',
          rows: 6,
          className: 'px-2 py-1.5 rounded-md text-xs font-mono bg-transparent border w-full',
          spellCheck: false,
        }}
        file={{
          mode: 'button',
          label: 'Choose a CSV file...',
          accept: '.csv,.txt,.tsv,.dat',
          onChoose: chooseFile,
          onBrowserFile: (name, text) => {
            setTable(parseTable(text), { filePath: name });
            onUi({ note: `Read ${name}` });
          },
        }}
        variable={{
          mode: 'multi',
          options: signalVars.map((v) => ({ name: v.name, hint: String(v.length) })),
          selected: ui.varNames,
          onChange: (varNames) => onUi({ varNames }),
          emptyText: 'None yet: run a script in the Code tab that creates numeric vectors.',
        }}
        note={ui.note}
        banner={table && table.problems.length > 0 ? { kind: 'error', text: table.problems.join(' '), compact: true } : null}
      />
      {hasTable && table && (
        <>
          <PreviewTable
            columns={stats.map((c) => c.name)}
            rows={table.columns[0].values.slice(0, 5).map((_, i) => table.columns.map((c) => (Number.isFinite(c.values[i]) ? formatSig(c.values[i], 6) : 'n/a')))}
            footer={[stats.map((c) => `n=${c.s.n}`), stats.map((c) => fmtRange(c.s.min, c.s.max)), stats.map((c) => `mean ${fmt(c.s.mean)}`)]}
          />
          <p className="text-xs" style={{ color: 'var(--qu-muted)' }}>
            {table.rows} rows, {table.columns.length} numeric columns{table.header ? ', header found' : ', no header'}, {table.delimiter}-separated.
          </p>
        </>
      )}
      {value.source !== 'example' && table && table.columns.length > 0 && (
        <div className="flex flex-col gap-2">
          {value.shape === 'yx' && (
            <>
              <div className="flex gap-2">
                {select('x column', value.cols.x, (v) => setCol({ x: v }), names)}
                {select('y column', value.cols.y, (v) => setCol({ y: v }), names)}
              </div>
              <div className="flex gap-2">
                <label className="flex flex-col gap-1 text-xs flex-1 min-w-0">
                  <span style={{ color: 'var(--qu-muted)' }}>Weights</span>
                  <select value={value.weight} onChange={(e) => onChange({ weight: e.target.value as FitSpec['weight'] })} className={inputClass} style={{ borderColor: border }}>
                    <option value="none">none</option>
                    <option value="sigma">y-error column (1/sigma)</option>
                    <option value="weight">weight column</option>
                  </select>
                </label>
                {value.weight !== 'none' && select(value.weight === 'sigma' ? 'y-error column' : 'weight column', value.cols.err, (v) => setCol({ err: v }), names)}
              </div>
            </>
          )}
          {value.shape === 'surface' && (
            <div className="flex gap-2">
              {select('x', value.cols.x, (v) => setCol({ x: v }), names)}
              {select('y', value.cols.y, (v) => setCol({ y: v }), names)}
              {select('z (fitted)', value.cols.z, (v) => setCol({ z: v }), names)}
            </div>
          )}
          {value.shape === 'multi' && (
            <>
              {select('time column', value.cols.t, (v) => setCol({ t: v, signals: value.cols.signals.filter((s) => s !== v) }), names)}
              <div className="flex flex-col gap-1 text-xs">
                <span style={{ color: 'var(--qu-muted)' }}>Signals to fit</span>
                {names.filter((n) => n !== value.cols.t).map((n) => (
                  <label key={n} className="flex items-center gap-2">
                    <input
                      type="checkbox"
                      checked={value.cols.signals.includes(n)}
                      onChange={(e) => setCol({ signals: e.target.checked ? [...value.cols.signals, n] : value.cols.signals.filter((s) => s !== n) })}
                    />
                    <span className="font-mono">{n}</span>
                  </label>
                ))}
              </div>
            </>
          )}
        </div>
      )}
    </div>
  );
};

const fmt = (v: number) => formatSig(v, 4);
const fmtRange = (a: number, b: number) => `${fmt(a)} to ${fmt(b)}`;

export default CurveFitData;
